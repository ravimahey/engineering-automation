"""Engineering Maintenance Report Generator.

Aggregates:
- Repository & workflow validation results
- Security & dependency audit results
- Automated test execution metrics (JUnit XML or fallback)
- Workflow execution context (UTC timestamp, commit SHA, runner details)

Generates or updates:
`reports/daily-maintenance.md` with executive metrics, security findings,
dependency matrix, recommendations, and persistent audit history.
"""

from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import re
import sys
from typing import Any, Dict, List, Optional
import xml.etree.ElementTree as ET


def parse_junit_xml(xml_path: Optional[Path]) -> Dict[str, Any]:
    """Parse JUnit XML generated by pytest."""
    metrics = {
        "total": 0,
        "passed": 0,
        "failures": 0,
        "errors": 0,
        "skipped": 0,
        "duration_seconds": 0.0,
        "status": "PASSED",
    }

    if not xml_path or not xml_path.is_file():
        return metrics

    try:
        tree = ET.parse(xml_path)
        root = tree.getroot()

        # Check if root is testsuites or testsuite
        if root.tag == "testsuites":
            suites = list(root.findall("testsuite"))
        else:
            suites = [root]

        total_tests = 0
        total_failures = 0
        total_errors = 0
        total_skipped = 0
        total_time = 0.0

        for suite in suites:
            total_tests += int(suite.attrib.get("tests", 0))
            total_failures += int(suite.attrib.get("failures", 0))
            total_errors += int(suite.attrib.get("errors", 0))
            total_skipped += int(suite.attrib.get("skipped", 0))
            total_time += float(suite.attrib.get("time", 0.0))

        passed = total_tests - (total_failures + total_errors + total_skipped)

        metrics["total"] = total_tests
        metrics["passed"] = max(0, passed)
        metrics["failures"] = total_failures
        metrics["errors"] = total_errors
        metrics["skipped"] = total_skipped
        metrics["duration_seconds"] = round(total_time, 2)

        if total_failures > 0 or total_errors > 0:
            metrics["status"] = "FAILED"
        else:
            metrics["status"] = "PASSED"

    except Exception as exc:
        print(f"Warning: Failed to parse JUnit XML {xml_path}: {exc}", file=sys.stderr)

    return metrics


def extract_existing_history(report_path: Path, max_entries: int = 30) -> List[str]:
    """Extract historical execution log rows from existing markdown report."""
    if not report_path.is_file():
        return []

    history_lines: List[str] = []
    in_history_section = False

    try:
        content = report_path.read_text(encoding="utf-8")
        for line in content.splitlines():
            if "## Execution History Log" in line:
                in_history_section = True
                continue
            if in_history_section:
                # Capture table rows starting with '| 20' (date)
                if re.match(r"^\|\s*20\d\d-\d\d-\d\d", line.strip()):
                    history_lines.append(line.strip())
                elif line.startswith("#"):
                    break
    except Exception:
        pass

    return history_lines[:max_entries]


def build_markdown_report(
    validation_data: Dict[str, Any],
    security_data: Dict[str, Any],
    test_metrics: Dict[str, Any],
    existing_history: List[str],
    git_sha: str = "local",
    event_name: str = "manual",
) -> str:
    """Construct production-grade Markdown maintenance report."""
    now_utc = datetime.now(timezone.utc)
    date_str = now_utc.strftime("%Y-%m-%d %H:%M:%S UTC")
    date_short = now_utc.strftime("%Y-%m-%d")

    # Determine overall status
    v_status = validation_data.get("overall_status", "UNKNOWN")
    s_status = security_data.get("overall_status", "UNKNOWN")
    t_status = test_metrics.get("status", "PASSED")

    statuses = [v_status, s_status, t_status]
    if "FAILED" in statuses:
        overall_status = "FAILED"
        status_badge = "🔴 FAILED"
    elif "WARNING" in statuses:
        overall_status = "WARNING"
        status_badge = "🟡 WARNING"
    else:
        overall_status = "PASSED"
        status_badge = "🟢 PASSED"

    # Collect issues
    issues: List[str] = []
    # Validation issues
    v_missing_files = validation_data.get("repository_structure", {}).get("missing_files", [])
    for f in v_missing_files:
        issues.append(f"Structure: Missing required repository file `{f}`")
    v_disallowed = validation_data.get("repository_structure", {}).get("disallowed_files", [])
    for f in v_disallowed:
        issues.append(f"Structure: Disallowed file present in repository: `{f}`")
    v_wf_issues = validation_data.get("workflow_configurations", {}).get("issues", [])
    for w in v_wf_issues:
        issues.append(f"Workflow Configuration: {w}")

    # Security findings
    sec_findings = security_data.get("secret_scanning", {}).get("findings", [])
    for finding in sec_findings:
        issues.append(
            f"Security: Detected potential secret ({finding['type']}) in `{finding['file']}:{finding['line']}`"
        )

    # Test failures
    if test_metrics["failures"] > 0 or test_metrics["errors"] > 0:
        issues.append(
            f"Testing: {test_metrics['failures']} failures and {test_metrics['errors']} errors detected during test run."
        )

    # Outdated packages
    outdated_pkgs = [
        p for p in security_data.get("dependency_health", {}).get("packages", [])
        if p.get("update_available")
    ]
    for p in outdated_pkgs:
        issues.append(
            f"Dependencies: Update available for `{p['package']}` (Current: `{p['current_version']}`, Latest: `{p['latest_version']}`)"
        )

    # Recommended actions
    recommendations: List[str] = []
    if sec_findings:
        recommendations.append("URGENT: Immediately revoke exposed credentials and sanitize git commit history.")
    if test_metrics["failures"] > 0 or test_metrics["errors"] > 0:
        recommendations.append("Inspect failed unit tests in CI log and fix regressions in scripts.")
    if outdated_pkgs:
        recommendations.append("Evaluate outdated Python packages and schedule version bumps in `requirements.txt`.")
    if v_wf_issues:
        recommendations.append("Review `.github/workflows/daily-maintenance.yml` against GitHub security requirements.")
    if not recommendations:
        recommendations.append("All daily engineering checks passed nominal thresholds. No remediation required.")

    # New History Row
    summary_cell = f"{test_metrics['passed']}/{test_metrics['total']} tests passed, {len(issues)} findings"
    new_history_row = (
        f"| {date_short} | {date_str} | {overall_status} | {event_name} | {git_sha[:8]} | {summary_cell} |"
    )

    # Filter out duplicate today's row if re-running on the exact same commit
    updated_history = [new_history_row]
    for row in existing_history:
        # Avoid exact duplicate row
        if row != new_history_row:
            updated_history.append(row)
    # Cap history at 20 entries
    updated_history = updated_history[:20]

    # Render Markdown
    md_lines = [
        "# Engineering Daily Maintenance Report",
        "",
        f"> **Generated at**: `{date_str}`  ",
        f"> **Execution Status**: {status_badge}  ",
        f"> **Trigger Event**: `{event_name}`  ",
        f"> **Commit Reference**: `{git_sha}`",
        "",
        "## Executive Summary",
        "",
        "| Category | Status | Details |",
        "| :--- | :--- | :--- |",
        f"| **Overall Health** | {status_badge} | Systematic daily verification complete |",
        f"| **Repository Structure** | {validation_data.get('repository_structure', {}).get('status', 'N/A')} | Required files, directories & clean tree |",
        f"| **YAML & Workflows** | {validation_data.get('workflow_configurations', {}).get('status', 'N/A')} | Syntactic compliance, permissions & action pinning |",
        f"| **Automated Tests** | {test_metrics.get('status', 'N/A')} | {test_metrics['passed']}/{test_metrics['total']} tests passed in {test_metrics['duration_seconds']}s |",
        f"| **Secret Scanning** | {security_data.get('secret_scanning', {}).get('status', 'N/A')} | {security_data.get('secret_scanning', {}).get('scanned_files_count', 0)} files audited |",
        f"| **Dependency Health** | {security_data.get('dependency_health', {}).get('status', 'N/A')} | {len(outdated_pkgs)} update(s) available |",
        "",
        "## Automated Activities Performed",
        "",
        "1. **Repository Structural Audit**: Validated directory hierarchy (`.github/workflows`, `scripts`, `reports`, `tests`), core files, and checked for prohibited temporary or cache files.",
        "2. **Configuration & Workflow Linting**: Verified YAML syntax integrity across repository configs; verified GitHub Actions permission scopes, SHA action pinning, and execution timeout bounds.",
        "3. **Security & Secret Scanning**: Audited code and markdown against credential patterns (AWS, GitHub PATs, private keys, generic tokens); inspected `.gitignore` rules.",
        "4. **Dependency Health Check**: Checked `requirements.txt` specifications and queried PyPI for upstream releases.",
        "5. **Unit Test Execution**: Ran regression test suite and generated structured execution metrics.",
        "6. **Report Compilation & Audit Trail**: Updated persistent maintenance log and synchronized repository health state.",
        "",
        "## Dependency Health Matrix",
        "",
        "| Package | Current Spec | Latest Version | Update Available | Status |",
        "| :--- | :--- | :--- | :---: | :--- |",
    ]

    for pkg in security_data.get("dependency_health", {}).get("packages", []):
        up_flag = "Yes" if pkg.get("update_available") else "No"
        md_lines.append(
            f"| `{pkg.get('package')}` | `{pkg.get('current_version')}` | `{pkg.get('latest_version')}` | {up_flag} | `{pkg.get('status')}` |"
        )

    md_lines.extend([
        "",
        "## Issues & Findings",
        "",
    ])

    if issues:
        for iss in issues:
            md_lines.append(f"- ⚠️ {iss}")
    else:
        md_lines.append("- ✅ **Zero anomalies detected**. Repository state adheres to all engineering and security standards.")

    md_lines.extend([
        "",
        "## Recommended Actions",
        "",
    ])

    for rec in recommendations:
        md_lines.append(f"1. {rec}")

    md_lines.extend([
        "",
        "## Execution History Log",
        "",
        "| Date | UTC Timestamp | Status | Trigger | Commit | Summary |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |",
    ])

    for hist_row in updated_history:
        md_lines.append(hist_row)

    md_lines.append("")  # Trailing newline

    return "\n".join(md_lines)


def main() -> int:
    """CLI entrypoint for report generation."""
    parser = argparse.ArgumentParser(description="Generate daily engineering maintenance report.")
    parser.add_argument(
        "--validation",
        type=Path,
        default=Path("reports/validation_results.json"),
        help="Path to validation JSON results.",
    )
    parser.add_argument(
        "--security",
        type=Path,
        default=Path("reports/security_results.json"),
        help="Path to security JSON results.",
    )
    parser.add_argument(
        "--test-xml",
        type=Path,
        default=Path("reports/test_results.xml"),
        help="Path to pytest JUnit XML results.",
    )
    parser.add_argument(
        "--report-out",
        type=Path,
        default=Path("reports/daily-maintenance.md"),
        help="Path to output markdown report.",
    )
    parser.add_argument(
        "--git-sha",
        type=str,
        default=os.environ.get("GITHUB_SHA", "local-dev"),
        help="Git commit SHA or reference.",
    )
    parser.add_argument(
        "--event-name",
        type=str,
        default=os.environ.get("GITHUB_EVENT_NAME", "workflow_dispatch"),
        help="Workflow trigger event name.",
    )
    args = parser.parse_args()

    # Load validation data
    validation_data: Dict[str, Any] = {}
    if args.validation.is_file():
        try:
            with open(args.validation, "r", encoding="utf-8") as f:
                validation_data = json.load(f)
        except Exception as exc:
            print(f"Warning: Failed to load {args.validation}: {exc}", file=sys.stderr)

    # Load security data
    security_data: Dict[str, Any] = {}
    if args.security.is_file():
        try:
            with open(args.security, "r", encoding="utf-8") as f:
                security_data = json.load(f)
        except Exception as exc:
            print(f"Warning: Failed to load {args.security}: {exc}", file=sys.stderr)

    # Load test metrics
    test_metrics = parse_junit_xml(args.test_xml)

    # Extract history from previous report
    existing_history = extract_existing_history(args.report_out)

    # Build report
    report_content = build_markdown_report(
        validation_data=validation_data,
        security_data=security_data,
        test_metrics=test_metrics,
        existing_history=existing_history,
        git_sha=args.git_sha,
        event_name=args.event_name,
    )

    args.report_out.parent.mkdir(parents=True, exist_ok=True)
    args.report_out.write_text(report_content, encoding="utf-8")
    print(f"[+] Maintenance report generated successfully at: {args.report_out}")

    return 0


if __name__ == "__main__":
    sys.exit(main())
